package app.notes_api;

import app.notes_api.exception.ResourceNotFoundException;
import app.notes_api.model.Note;
import app.notes_api.repository.NoteRepository;
import app.notes_api.service.NoteService;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.Collections;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class NoteServiceTest {

    @Mock
    private NoteRepository noteRepository;

    @InjectMocks
    private NoteService noteService;

    @Test
    void validNoteCreationReturnsCreatedNoteWithAutoGeneratedId() {
        // Arrange
        String title = "Meeting Notes";
        String body = "Discuss project timeline";
        long generatedId = 1L;
        Note expectedNote = new Note(generatedId, title, body);

        // Use any() matcher since the service creates a new Note internally
        when(noteRepository.createNote(any(Note.class))).thenReturn(expectedNote);

        // Act
        Note result = noteService.createNote(title, body);

        // Assert
        assertNotNull(result);
        assertEquals(generatedId, result.getId());
        assertEquals(title, result.getTitle());
        assertEquals(body, result.getBody());
        verify(noteRepository, times(1)).createNote(any(Note.class));
    }

    @Test
    void blankTitleThrowsIllegalArgumentException() {
        // Arrange
        String blankTitle = "   ";
        String body = "Some body";

        // Act & Assert
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> {
            noteService.createNote(blankTitle, body);
        });
        assertEquals("Title must not be blank", exception.getMessage());
        verify(noteRepository, never()).createNote(any());
    }

    @Test
    void nonExistentNoteIdThrowsResourceNotFoundException() {
        // Arrange
        long nonExistentId = 999L;
        when(noteRepository.getById(nonExistentId)).thenReturn(null);

        // Act & Assert
        ResourceNotFoundException exception = assertThrows(ResourceNotFoundException.class, () -> {
            noteService.getById(nonExistentId);
        });
        assertEquals("Note not found", exception.getMessage());
    }

    @Test
    void updateWithValidDataReturnsUpdatedNote() {
        // Arrange
        long id = 1L;
        String newTitle = "Updated Title";
        String newBody = "Updated Body";
        Note existingNote = new Note(id, "Old Title", "Old Body");
        Note expectedUpdatedNote = new Note(id, newTitle, newBody);

        when(noteRepository.getById(id)).thenReturn(existingNote);
        // Use any() matcher since the service creates a new Note internally
        when(noteRepository.updateNote(any(Note.class))).thenReturn(1);

        // Act
        Note result = noteService.updateNote(id, newTitle, newBody);

        // Assert
        assertNotNull(result);
        assertEquals(id, result.getId());
        assertEquals(newTitle, result.getTitle());
        assertEquals(newBody, result.getBody());
        verify(noteRepository, times(1)).updateNote(any(Note.class));
    }

    @Test
    void deleteNonExistentNoteThrowsResourceNotFoundException() {
        // Arrange
        long nonExistentId = 999L;
        when(noteRepository.getById(nonExistentId)).thenReturn(null);

        // Act & Assert
        ResourceNotFoundException exception = assertThrows(ResourceNotFoundException.class, () -> {
            noteService.deleteNote(nonExistentId);
        });
        assertEquals("Note not found", exception.getMessage());
        verify(noteRepository, never()).deleteNote(anyLong());
    }
}
