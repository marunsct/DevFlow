"""Postgres-backed persistence for plugin instructions."""

import os
import threading
from contextlib import contextmanager
from typing import Any, Optional, Dict

import psycopg2
from psycopg2.pool import ThreadedConnectionPool

from app.server.process_local import owned_here
from app.server.schema_lock import lock_schema

_CREATE_TABLE = """
CREATE TABLE IF NOT EXISTS plugin_instructions (
    framework_name TEXT PRIMARY KEY,
    instructions TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
"""

#: The first line of every generated row, naming the prompt that wrote it.
#: Generated rows without the current marker are deleted at seeding, so the
#: framework is generated again under the current prompt the next time a stack
#: names it. The previous prompt asked for "best practices ... concurrency,
#: security and architecture", and a to-do list app's specialists were told to
#: "Use Web Workers for CPU-heavy tasks" and "Adopt CSP headers".
GENERATED_MARKER = "<!-- generated-v2 -->"


def database_url() -> str:
    return os.environ.get("DB_URL", "postgresql://postgres:postgres@localhost:5432/postgres")


class PluginStore:
    """Store for framework-specific plugin instructions."""

    _shared: Optional["PluginStore"] = None
    _shared_owner: Optional[int] = None
    _shared_lock = threading.Lock()

    def __init__(self, db_url: str | None = None) -> None:
        self._pool = ThreadedConnectionPool(1, 10, db_url or database_url())
        self._ensure_schema()
        self._seed_default_instructions()

    @classmethod
    def shared(cls) -> "PluginStore":
        # Per process, not per class: a store built in the Celery parent is
        # inherited by every worker it forks later, and two processes on one
        # connection is a dropped connection. See `app.server.process_local`.
        with cls._shared_lock:
            if cls._shared is None or not owned_here(cls._shared_owner):
                cls._shared = cls()
                cls._shared_owner = os.getpid()
            return cls._shared

    def _ensure_schema(self) -> None:
        with self.get_connection() as conn:
            with conn.cursor() as cur:
                lock_schema(cur)
                cur.execute(_CREATE_TABLE)
                # Provenance, for `_seed_default_instructions`. Added rather
                # than declared so a table created before them gains them.
                cur.execute("ALTER TABLE plugin_instructions ADD COLUMN IF NOT EXISTS origin TEXT")
                cur.execute(
                    "ALTER TABLE plugin_instructions ADD COLUMN IF NOT EXISTS seeded_instructions TEXT"
                )
            conn.commit()

    @contextmanager
    def get_connection(self):
        conn = self._pool.getconn()
        try:
            yield conn
        except Exception:
            conn.rollback()
            raise
        finally:
            try:
                conn.rollback()
            except Exception:
                pass
            self._pool.putconn(conn)

    def _seed_default_instructions(self) -> None:
        """Write the seed rows, refreshing any that still hold their seeded text.

        The seed lives in `app.plugins.seed`. It used to be written with
        `ON CONFLICT DO NOTHING`, which protected an edited row but also meant a
        revised seed never reached a database that had already been seeded - the
        rows kept their first text for ever. Each row now records where it came
        from and what it was seeded with, and a seed row is refreshed only when:

        - it still holds exactly the text it was seeded with, so nobody has
          edited it, or
        - it was generated by the middleware before a curated seed existed for
          that name, which is a model's guess and not anyone's decision, or
        - it predates this bookkeeping (`seeded_instructions` is NULL), and so
          was written by an earlier seed.

        A row whose text differs from what was seeded was changed by hand, and
        is left alone.
        """
        from app.plugins.seed import SEED_INSTRUCTIONS

        with self.get_connection() as conn:
            with conn.cursor() as cur:
                for framework, instructions in SEED_INSTRUCTIONS.items():
                    cur.execute(
                        "INSERT INTO plugin_instructions "
                        "(framework_name, instructions, origin, seeded_instructions) "
                        "VALUES (%s, %s, 'seed', %s) "
                        "ON CONFLICT (framework_name) DO UPDATE SET "
                        "instructions = EXCLUDED.instructions, "
                        "seeded_instructions = EXCLUDED.seeded_instructions, "
                        "origin = 'seed', updated_at = CURRENT_TIMESTAMP "
                        "WHERE plugin_instructions.origin = 'generated' "
                        "OR plugin_instructions.seeded_instructions IS NULL "
                        "OR plugin_instructions.instructions = plugin_instructions.seeded_instructions",
                        (framework.lower(), instructions, instructions),
                    )
                cur.execute(
                    "DELETE FROM plugin_instructions WHERE origin = 'generated' "
                    "AND instructions NOT LIKE %s",
                    (GENERATED_MARKER + "%",),
                )
            conn.commit()

    def get_instructions(self, framework_name: str) -> Optional[str]:
        with self.get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT instructions FROM plugin_instructions WHERE framework_name = %s", (framework_name.lower(),))
                row = cur.fetchone()
                if row:
                    text = str(row[0] or "")
                    return text[len(GENERATED_MARKER):].lstrip("\n") if text.startswith(GENERATED_MARKER) else text
        return None

    def get_all_framework_names(self) -> list[str]:
        with self.get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT framework_name FROM plugin_instructions")
                return [row[0] for row in cur.fetchall()]

    def update_instructions(self, framework_name: str, instructions: str) -> None:
        with self.get_connection() as conn:
            with conn.cursor() as cur:
                # Marked generated, so a curated seed for the same name can
                # replace it later; see `_seed_default_instructions`.
                cur.execute(
                    "INSERT INTO plugin_instructions (framework_name, instructions, origin) "
                    "VALUES (%s, %s, 'generated') "
                    "ON CONFLICT (framework_name) DO UPDATE SET instructions = EXCLUDED.instructions, "
                    "origin = 'generated', updated_at = CURRENT_TIMESTAMP",
                    (framework_name.lower(), f"{GENERATED_MARKER}\n{instructions}")
                )
            conn.commit()
