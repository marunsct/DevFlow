"""Write the API's OpenAPI schema and the UI's types generated from it (plan UI-0).

    ENV=development PYTHONPATH=src .venv/bin/python scripts/ui/openapi_schema.py

writes `langchain-ui/openapi.json` and `langchain-ui/src/types/api.gen.ts`. The
UI's types of what the server sends and accepts come from the second, so a
field renamed on one side and not the other fails the UI's build instead of
reading `undefined` on a page - the run list read `documents` for months after
the server called it `document_names`.
`tests/test_the_ui_s_api_types_are_current.py` fails when the server's schema
moves and these files were not written again.

The application is built with its store and runner stood in: the schema is the
routes' and the models', and needs no database. The types are generated here,
not by `openapi-typescript`, which supports TypeScript 5 only, and so that the
suite checks them with no Node: FastAPI's schemas use a handful of keywords.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any
from unittest.mock import MagicMock, patch

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "langchain-ui" / "openapi.json"
TYPES = ROOT / "langchain-ui" / "src" / "types" / "api.gen.ts"


def current_schema() -> str:
    """The server's OpenAPI schema as the file holds it: sorted keys, one space of indent."""
    with patch("app.server.run_store.RunStore.shared", return_value=MagicMock()), patch(
        "app.server.runner.WorkflowRunner", MagicMock()
    ):
        from app.server.api import create_app

        schema = create_app().openapi()
    return json.dumps(schema, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def _named(node: Any) -> set[str]:
    found: set[str] = set()

    def walk(value: Any) -> None:
        if isinstance(value, dict):
            if "$ref" in value:
                found.add(value["$ref"].rsplit("/", 1)[-1])
            for inner in value.values():
                walk(inner)
        elif isinstance(value, list):
            for inner in value:
                walk(inner)

    walk(node)
    return found


def _sent_by_the_server(schema: dict) -> set[str]:
    """The schemas a response carries, through every reference."""
    schemas = schema["components"]["schemas"]
    todo = [name for ops in schema["paths"].values() for op in ops.values() for name in _named(op.get("responses", {}))]
    seen: set[str] = set()
    while todo:
        name = todo.pop()
        if name not in seen:
            seen.add(name)
            todo.extend(_named(schemas[name]))
    return seen


def _type(node: dict) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in node or "oneOf" in node:
        parts = [_type(part) for part in node.get("anyOf") or node.get("oneOf")]
        return " | ".join(dict.fromkeys(parts))
    if "enum" in node:
        return " | ".join(json.dumps(value) for value in node["enum"])
    kind = node.get("type")
    if kind == "string":
        return "Blob" if node.get("format") == "binary" or "contentMediaType" in node else "string"
    if kind in ("integer", "number"):
        return "number"
    if kind in ("boolean", "null"):
        return kind
    if kind == "array":
        item = _type(node.get("items") or {})
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object" or "properties" in node:
        if node.get("properties"):
            return "{ " + " ".join(f"{_key(k)}: {_type(v)};" for k, v in node["properties"].items()) + " }"
        extra = node.get("additionalProperties")
        return f"Record<string, {_type(extra)}>" if isinstance(extra, dict) and extra else "Record<string, unknown>"
    return "unknown"


def _key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


def _comment(text: str | None, indent: str) -> str:
    if not text:
        return ""
    words = " ".join(text.split()).replace("*/", "* /")
    return f"{indent}/** {words} */\n"


def typescript(schema_text: str) -> str:
    """The TypeScript interfaces of the schema's components.

    A response's model always serializes every field, so in what the server
    sends each property is present; in what it accepts, only `required` ones
    must be.
    """
    schema = json.loads(schema_text)
    sent = _sent_by_the_server(schema)
    out = [
        "/* Generated by scripts/ui/openapi_schema.py from openapi.json: do not edit by hand. */\n",
        "/* eslint-disable */\n",
    ]
    for name, node in sorted(schema["components"]["schemas"].items()):
        out.append("\n" + _comment(node.get("description"), ""))
        if "properties" not in node:
            out.append(f"export type {name} = {_type(node)};\n")
            continue
        required = set(node.get("required") or [])
        out.append(f"export interface {name} {{\n")
        for prop, value in node["properties"].items():
            optional = "" if name in sent or prop in required else "?"
            out.append(_comment(value.get("description"), "  "))
            out.append(f"  {_key(prop)}{optional}: {_type(value)};\n")
        out.append("}\n")
    return "".join(out)


if __name__ == "__main__":
    text = current_schema()
    SCHEMA.write_text(text)
    TYPES.write_text(typescript(text))
    print(f"wrote {SCHEMA.relative_to(ROOT)} and {TYPES.relative_to(ROOT)}")
