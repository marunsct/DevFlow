"""Framework instructions have to reach the model, and cost what they say.

The feature is the harness's answer to being technology-agnostic: the shared
prompts hold for every stack, and whatever is true only of one framework is
stored per framework and appended for the runs that use it - generated by the
model for a framework the store has never seen, so nothing has to maintain a
list of supported technologies.

Its first implementation appended to `request.messages[0]`, expecting the system
prompt to be there. `ModelRequest.messages` excludes the system prompt, so the
branch never ran: every run paid for the extraction calls and no instruction was
ever injected. And the extraction ran per model call rather than per stack, so a
stage making 160 calls made 160 extractions of one unchanged document.

Both are asserted here against a fake model, so neither can come back and
neither test needs a network.
"""

from __future__ import annotations

from typing import Any

import pytest

from app.plugins import middleware as plugin_middleware


class _FakeReply:
    def __init__(self, content: Any) -> None:
        self.content = content


class _FakeModel:
    """Counts its calls, and answers the extraction and generation prompts."""

    def __init__(self, frameworks: str = "react, typescript") -> None:
        self.frameworks = frameworks
        self.calls: list[str] = []

    def invoke(self, messages: list[Any]) -> _FakeReply:
        prompt = str(getattr(messages[0], "content", ""))
        self.calls.append(prompt)
        if "tech stack analyzer" in prompt:
            return _FakeReply(self.frameworks)
        return _FakeReply("- Do the framework-specific thing")


class _FakeStore:
    def __init__(self, known: dict[str, str] | None = None) -> None:
        self.instructions = dict(known or {})

    def get_all_framework_names(self) -> list[str]:
        return list(self.instructions)

    def get_instructions(self, name: str) -> str | None:
        return self.instructions.get(name.lower())

    def update_instructions(self, name: str, instructions: str) -> None:
        self.instructions[name.lower()] = instructions


@pytest.fixture
def stack(tmp_path):
    """A workspace with a stack document in it."""
    docs = tmp_path / "docs"
    docs.mkdir()
    (docs / "technology_stack.md").write_text("Frontend: React with TypeScript.", encoding="utf-8")
    return tmp_path


@pytest.fixture
def wired(monkeypatch, stack):
    """The middleware with a fake model and a fake store, and a clean cache."""
    model = _FakeModel()
    store = _FakeStore({"typescript": "Use npm and respect the lockfile."})
    monkeypatch.setattr(plugin_middleware, "_extraction_model", lambda: model)
    monkeypatch.setattr(plugin_middleware, "_CACHE", {})

    class _Store:
        @staticmethod
        def shared():
            return store

    monkeypatch.setitem(
        __import__("sys").modules, "app.server.plugin_store",
        type("module", (), {"PluginStore": _Store}),
    )
    from app.plugins import registry

    monkeypatch.setattr(registry.PluginStore, "shared", staticmethod(lambda: store))
    return model, store, stack


class _Request:
    """The shape of a `ModelRequest` this middleware touches."""

    def __init__(self, system_message: Any = None, system_prompt: str | None = None,
                 messages: list | None = None) -> None:
        from langchain_core.messages import SystemMessage

        self.system_message = (
            SystemMessage(content=system_message) if isinstance(system_message, str) else system_message
        )
        self.system_prompt = system_prompt
        self.messages = messages if messages is not None else [{"role": "user", "content": "go"}]

    def override(self, **fields: Any) -> "_Request":
        clone = _Request(self.system_message, self.system_prompt, list(self.messages))
        for name, value in fields.items():
            setattr(clone, name, value)
        return clone


class TestTheInstructionsReachTheModel:
    def test_they_are_appended_to_the_system_prompt_not_to_messages(self, wired):
        """The bug that made the whole feature inert.

        `messages[0]` is the first *conversation* message. Appending there put
        framework instructions into a user turn at best, and in practice into
        nothing at all, because the old code required that message to be a dict
        with `role == "system"` and it never is.
        """
        model, store, stack = wired
        received: dict[str, Any] = {}

        built = plugin_middleware.build_plugin_instructions_middleware(str(stack))
        built.wrap_model_call(
            _Request(system_message="You are the backend specialist."),
            lambda request: received.setdefault("request", request),
        )

        prompt = received["request"].system_message.content
        assert prompt.startswith("You are the backend specialist.")
        assert "Use npm and respect the lockfile." in prompt, "the stored instruction was injected"
        assert received["request"].messages == [{"role": "user", "content": "go"}], (
            "the conversation is left alone"
        )

    def test_a_deprecated_system_prompt_string_is_handled_too(self, wired):
        model, store, stack = wired
        received: dict[str, Any] = {}

        built = plugin_middleware.build_plugin_instructions_middleware(str(stack))
        built.wrap_model_call(
            _Request(system_prompt="You are the backend specialist."),
            lambda request: received.setdefault("request", request),
        )

        assert "Use npm and respect the lockfile." in received["request"].system_message.content

    def test_a_stack_with_no_document_costs_nothing(self, wired, tmp_path):
        """Early stages have not chosen a stack; they must not pay for one."""
        model, store, _ = wired
        received: dict[str, Any] = {}

        built = plugin_middleware.build_plugin_instructions_middleware(str(tmp_path / "empty"))
        built.wrap_model_call(_Request(system_message="p"), lambda r: received.setdefault("r", r))

        assert model.calls == []
        assert received["r"].system_message.content == "p"


class TestWhatItCosts:
    def test_the_stack_is_read_once_however_many_calls_are_made(self, wired):
        """One extraction per stack, not per model call.

        Uncached, a stage making 160 calls made 160 extraction calls plus one
        generation call per unknown framework per call. The document changes at
        most once in a run.
        """
        model, store, stack = wired
        built = plugin_middleware.build_plugin_instructions_middleware(str(stack))

        for _ in range(25):
            built.wrap_model_call(_Request(system_message="p"), lambda r: r)

        extractions = [call for call in model.calls if "tech stack analyzer" in call]
        assert len(extractions) == 1, f"one extraction expected, made {len(extractions)}"

    def test_a_rewritten_stack_is_read_again(self, wired):
        """The cache is keyed on the document, so a new stack is not stale."""
        model, store, stack = wired
        built = plugin_middleware.build_plugin_instructions_middleware(str(stack))

        built.wrap_model_call(_Request(system_message="p"), lambda r: r)
        (stack / "docs" / "technology_stack.md").write_text("Backend: Go.", encoding="utf-8")
        model.frameworks = "go"
        built.wrap_model_call(_Request(system_message="p"), lambda r: r)

        assert len([c for c in model.calls if "tech stack analyzer" in c]) == 2

    def test_an_unknown_framework_gets_instructions_generated_and_kept(self, wired):
        """The agnostic half: no list of supported frameworks anywhere."""
        model, store, stack = wired
        model.frameworks = "elixir"
        built = plugin_middleware.build_plugin_instructions_middleware(str(stack))

        built.wrap_model_call(_Request(system_message="p"), lambda r: r)

        assert "elixir" in store.instructions
        assert "framework-specific thing" in store.instructions["elixir"]

    def test_a_framework_is_generated_for_once_not_once_per_call(self, wired):
        model, store, stack = wired
        model.frameworks = "elixir"
        built = plugin_middleware.build_plugin_instructions_middleware(str(stack))

        for _ in range(10):
            built.wrap_model_call(_Request(system_message="p"), lambda r: r)

        generations = [call for call in model.calls if "best practices" in call]
        assert len(generations) == 1


class TestParsingTheModelSAnswer:
    @pytest.mark.parametrize("reply, expected", [
        ("react, typescript", ["react", "typescript"]),
        ("React, TypeScript, Postgres", ["react", "typescript", "postgres"]),
        ("- react\n- node", ["react", "node"]),
        ("`react`, *node*", ["react", "node"]),
        ("react, react, node", ["react", "node"]),
    ])
    def test_names_are_normalised(self, reply, expected):
        assert plugin_middleware._framework_names(reply) == expected

    def test_a_sentence_is_not_a_framework(self):
        """It became a row in the store, keyed by the sentence.

        With instructions generated for it - a model asked for "best practices
        for the 'i cannot determine the frameworks from this document' framework"
        answers, at length, and that answer was then appended to a specialist's
        system prompt.
        """
        reply = "I cannot determine the frameworks from this document."

        assert plugin_middleware._framework_names(reply) == []

    def test_an_answer_that_is_a_whole_essay_is_bounded(self):
        reply = ", ".join(f"framework{index}" for index in range(50))

        assert len(plugin_middleware._framework_names(reply)) == plugin_middleware._MOST_FRAMEWORKS

    @pytest.mark.parametrize("content, expected", [
        ("react, node", "react, node"),
        ([{"type": "text", "text": "react"}, {"type": "text", "text": "node"}], "react\nnode"),
        (["react", "node"], "react\nnode"),
        (None, ""),
    ])
    def test_content_blocks_are_read_as_text(self, content, expected):
        """A provider that returns blocks must not silently disable the feature."""
        assert plugin_middleware._text_of(_FakeReply(content)) == expected
