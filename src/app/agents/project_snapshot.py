"""The project's files, handed to a stage at its start when the project is small.

Every stage begins with a fresh conversation and finds out what the project
says one `read_file` at a time. Measured on one completed run of a ten-file,
347-line product: 82% of its 911 tool calls were reads, listings and searches
against 8% that wrote anything; `ui.js` was read 60 times, `package.json` and
the unit tests 36 times each, across 27 stages. Every one of those calls is a
model turn - the prompt read again and reasoned over before the next move.

For a project that small the whole of it is a few thousand tokens. Put in the
stage's opening request it is read once, kept in the server's prompt cache for
the rest of the stage, and the first round of reading is not needed.

Only up to `SNAPSHOT_BUDGET_CHARS`. A larger project gets nothing from here and
keeps the workspace listing it already has (`app.agents.workspace_digest`) -
the product's code first and its tests and configuration after, so what is cut
at the budget is the least needed, and named.

A snapshot, not a live view. A parallel sibling can change a file after the
stage starts, so each file carries its line count at the time, and the
listing at the end of every request carries the current one: a count that
differs says to read the file again before changing it. The line-range edit
tools also refuse a change whose expected lines are not there.
"""

from __future__ import annotations

import logging
import time
from pathlib import Path

logger = logging.getLogger(__name__)

#: The most of the project put in an opening request, in characters - about
#: 6,000 tokens, a few seconds of prompt processing once per stage.
SNAPSHOT_BUDGET_CHARS = 24_000

#: Generated by a package manager, read by nobody: a lockfile is longer than
#: the product it locks and says nothing a stage acts on.
_LOCKFILE_NAMES = frozenset({
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "Pipfile.lock",
    "Cargo.lock", "composer.lock", "Gemfile.lock", "go.sum", "uv.lock", "bun.lockb",
})


def _when() -> str:
    """The clock, or a time-free phrase under `CANONICAL_MEMORY` (plan PX.3)."""
    from app.agents.canonical_memory import when

    return when(time.strftime("%H:%M:%S"))


def _numbered(text: str) -> str:
    """`text` numbered the way `read_file` numbers it, so a line range carries over."""
    try:
        from deepagents.backends.utils import format_content_with_line_numbers

        return format_content_with_line_numbers(text, start_line=1)
    except Exception:  # noqa: BLE001 - numbering is a convenience
        return "\n".join(f"{number:>6}  {line}" for number, line in enumerate(text.splitlines(), 1))


def _readable(path: Path) -> str | None:
    """The file's text, or None when it is not text a stage should be shown."""
    try:
        data = path.read_bytes()
    except OSError:
        return None
    if b"\x00" in data[:4096]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def _later_sprints_files(root: Path) -> dict[str, list[str]]:
    """The locked suite files that are wholly a later sprint's. Never raises."""
    try:
        from app.acceptance.sprint_scope import later_sprints_files

        return later_sprints_files(root)
    except Exception:  # noqa: BLE001 - a snapshot without this shows everything
        return {}


def project_snapshot(repo_root: str | Path, only_whether_empty: bool = False) -> str:
    """The project's files with numbered lines, or "" when there is no project or it is too big.

    With `only_whether_empty`, the empty-project notice or "" - read no further
    than the first file with something in it. Under the project memory that is
    all a stage is given from here, and every file of the project was read for
    it at each stage's start; on a large project, all of them every time.

    Never raises: a stage without a snapshot reads files, as it always has.
    """
    try:
        from app.analysis.file_kinds import classify_file
        from app.tools.repository import HARNESS_FILES, list_repository_files, pinned_project_directory

        root = Path(repo_root)
        project = pinned_project_directory(root)
        if not project:
            return ""
        names = [
            name for name in list_repository_files(root)
            if name.startswith(f"{project}/")
            and Path(name).name not in _LOCKFILE_NAMES
            and Path(name).name not in HARNESS_FILES
        ]
        files: list[tuple[str, str]] = []
        for name in names:
            text = _readable(root / name)
            if text is not None and text.strip():
                if only_whether_empty:
                    return ""
                files.append((name, text))
        if not files:
            # Said, not left silent. With no snapshot a stage goes to look: one
            # run's architect spent three turns - `ls` twice, a change query
            # and `glob **/*` - finding an empty directory, about four minutes
            # on a model that writes 2,000-4,000 tokens a turn.
            return (
                f"The project directory `{project}/` has no files yet "
                f"({_when()}): nothing has been built, so there is "
                "nothing in it to list, search or read. What this stage works from is "
                "in this request and the documents under `docs/`."
            )
        # The product's own code first, so the budget cuts tests and
        # configuration before it cuts what they are about.
        files.sort(key=lambda item: (classify_file(item[0]) != "application", item[0]))

        shown: list[str] = []
        left_out: list[str] = []
        later = _later_sprints_files(root)
        held_back: list[str] = []
        used = 0
        for name, text in files:
            lines = len(text.splitlines())
            if name in later:
                # A later sprint's tests, inlined in full, read as this stage's
                # work. See `app.acceptance.sprint_scope`.
                held_back.append(f"{name} ({', '.join(later[name])})")
                continue
            block = f"--- {name} ({lines} lines) ---\n{_numbered(text)}\n"
            if used + len(block) > SNAPSHOT_BUDGET_CHARS:
                left_out.append(f"{name} ({lines} lines)")
                continue
            shown.append(block)
            used += len(block)
        if not shown:
            return ""
        omitted = (
            "\nNot included, to keep this short - read these if you need them: "
            + ", ".join(left_out) + "."
            if left_out else ""
        ) + (
            "\nNot included because every test in them is for a criterion a later "
            "sprint builds: " + ", ".join(held_back) + "."
            if held_back else ""
        )
        return (
            f"The project's files as they stood when this stage started "
            f"({_when()}), numbered the way `read_file` numbers them. "
            "You do not need to read a file below to know what it says. Another "
            "task may change a file after this point: the workspace listing at the "
            "end of each request gives every file's current line count, and if it "
            "differs from the count here, read that file again before you change it."
            + omitted + "\n\n" + "\n".join(shown)
        )
    except Exception:  # noqa: BLE001 - never fail a stage over a convenience
        logger.debug("Could not build the project snapshot", exc_info=True)
        return ""


def for_a_stage(repo_root: str | Path) -> str:
    """What a stage's opening request is given: the snapshot, or only the empty-project notice under the project memory.

    Every stage agent carries the project memory (`app.agents.project_memory`),
    which holds the same files whole at the start of every call and names what
    it left out. The snapshot on top of it said each file twice and
    contradicted it: measured on a Measure run, every call of a fix stage
    carried 14 files twice - about 24,000 characters - and the snapshot called
    a test file "not included, read it" that the memory held and refused to
    let it read; the fixer concluded the memory held only summaries.
    """
    from app.agents import project_memory

    under_the_memory = project_memory.enabled()
    text = project_snapshot(repo_root, only_whether_empty=under_the_memory)
    if text and under_the_memory and not text.startswith("The project directory `"):
        return ""
    return text


__all__ = ["SNAPSHOT_BUDGET_CHARS", "for_a_stage", "project_snapshot"]
